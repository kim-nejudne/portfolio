/** The sample's images as blobs, keyed by `imageId`, for the image table. */
export function sampleImages(): { id: string; blob: Blob }[] {
  return Object.entries(PNG_BASE64).map(([id, base64]) => {
    const bytes = Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));
    return { id, blob: new Blob([bytes], { type: 'image/png' }) };
  });
}
