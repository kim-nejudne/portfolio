// Types shared by the server and the client. The Data model section of docs/SPEC.md is the source.
// Runtime validation lives in schemas.ts; its inferred types are checked against these.

// ---------- Saved in the browser (editor) ----------

export interface QuestionSet {
  id: string; // nanoid
  title: string;
  questions: Question[];
  createdAt: number;
  updatedAt: number;
  schemaVersion: 1;
  category?: string; // 1–40 characters
  difficulty?: Difficulty;
}

export type Difficulty = 'easy' | 'medium' | 'hard';

export interface Question {
  id: string;
  text: string; // may be '' if imageId is set
  imageId?: string; // key into the image store
  answer: string;
  hostNotes?: string;
  points: number; // default 100
}

// ---------- Server room state (in memory) ----------

export type Phase =
  | 'LOBBY'
  | 'QUESTION' // shown, buzzers locked
  | 'OPEN' // buzzers open
  | 'COLLECTING' // first buzz received, 150 ms window
  | 'BUZZED' // winner shown, waiting for host judgement
  | 'REVEAL' // answer shown
  | 'FINAL';

export interface Player {
  id: string; // playerId, generated by client, stored on device
  name: string;
  color: string; // from palette
  score: number;
  connected: boolean;
  rttMs: number; // rolling median
  joinedAt: number;
  avatar?: string; // one of `AVATARS`; absent when the player picked none (F74)
  /** `openingCounter` at join. A player can buzz from the next opening (Edge cases; DECISIONS F14). */
  joinedAtOpening: number;
  team: number | null; // index into `TEAMS`; null when teams are off (F81)
}

export interface Buzz {
  playerId: string;
  receivedAt: number; // server monotonic ms
  oneWayMs: number;
  adjustedAt: number;
}

export interface Judgement {
  questionIndex: number;
  playerId: string;
  result: 'correct' | 'half' | 'wrong';
  pointsDelta: number;
}

/**
 * What `host:undo` restores: the opening's buzzes and winner as they were when the host judged.
 * Every judgement pushes one onto `Room.undo` and each undo pops one; the stack clears when the
 * question changes, so undo walks back through this question's judgements only (DECISIONS #6, F68).
 */
export interface UndoPoint {
  buzzes: Buzz[];
  windowStartedAt: number | null;
  winnerId: string;
}

/** Who a session total belongs to, as last tallied, so a player who left still has a name. */
export interface SessionPlayer {
  name: string;
  color: string;
  avatar?: string;
  joinedAt: number;
}

/** The night's games in this room (F76). Totals add each game's points at FINAL. */
export interface Session {
  gameNumber: number; // 1 for the room's first game; `host:newGame` adds 1
  totals: Record<string, number>; // playerId → points over every finished game
  // SPEC-QUESTION: players and carried are not in the spec's session; see DECISIONS (F76).
  players: Record<string, SessionPlayer>; // playerId → identity at their last tally
  carried: Record<string, number>; // playerId → score brought into this game by Keep scores
}

/** Seconds the buzz winner has to answer; 0 turns the answer timer off. */
export type AnswerSeconds = 0 | 3 | 5 | 7 | 10;

/** Seconds the players have to buzz once the buzzers open; 0 turns the buzz timer off. */
export type BuzzSeconds = 0 | 5 | 10 | 15 | 20 | 30;

/** Ms a false-started player waits after the buzzers open; 0 turns false starts off. */
export type FalseStartMs = 0 | 500 | 1000;

/** How many teams play; 0 turns teams off. */
export type TeamCount = 0 | 2 | 3 | 4;

export interface RoomSettings {
  wrongPenalty: boolean; // default false
  autoOpenBuzzers: boolean; // default false
  scoreboardEvery: number; // default 5, 0 = never auto
  answerSeconds: AnswerSeconds; // default 0 = off
  buzzSeconds: BuzzSeconds; // default 0 = off
  falseStartMs: FalseStartMs; // default 0 = off
  showStandings: boolean; // default true: the Screen's top-5 rail during a question
  teams: TeamCount; // default 0 = off
}

/** The buzz winner's answer time. `endsAt` is wall-clock ms and never leaves the server. */
export interface AnswerTimer {
  seconds: number;
  endsAt: number;
  up: boolean;
}

/** The time left to buzz in this opening. `endsAt` is wall-clock ms and never leaves the server. */
export interface BuzzTimer {
  seconds: number;
  endsAt: number;
}

export interface Room {
  code: string;
  hostTokenHash: string; // store a hash, never the raw token
  set: QuestionSet; // without image blobs
  settings: RoomSettings;
  players: Record<string, Player>;
  kickedIds: string[];
  phase: Phase;
  questionIndex: number; // -1 in lobby
  openingCounter: number; // increments each time buzzers open
  buzzes: Buzz[]; // for the current opening
  windowStartedAt: number | null; // monotonic receivedAt of the opening's first buzz
  // SPEC-QUESTION: openedAt and falseStarts are not in the spec's Room; see DECISIONS (F71).
  openedAt: number | null; // monotonic ms when this opening began; null if the gateway gave none
  falseStarts: string[]; // playerIds who pressed in QUESTION, until a later opening of the question
  winnerId: string | null;
  lockedOut: string[]; // playerIds wrong this question
  judgements: Judgement[]; // whole game, enables undo
  reopenAt: number | null; // wall-clock ms; set in BUZZED while a wrong answer waits to reopen
  undo: UndoPoint[]; // one per judgement of this question, newest last
  answerTimer: AnswerTimer | null; // set in BUZZED while the winner's answer time runs
  buzzTimer: BuzzTimer | null; // set in OPEN while the buzz time runs
  autoOpenAt: number | null; // wall-clock ms; set in QUESTION while question 1's title card holds auto-open
  hostDevices: number; // connected host remotes (not a Screen holding the token)
  session: Session; // the night's games in this room
  showScoreboard: boolean; // overlay, independent of phase
  createdAt: number;
  lastActivityAt: number;
}

// ---------- Role-filtered views (built by toView in server/views.ts) ----------

export type Role = 'screen' | 'host' | 'player';

/** A buzz that lost, with its gap to the winner. Rank order, winner excluded (DECISIONS #13). */
export interface BuzzGap {
  playerId: string;
  gapMs: number;
}

/** A player as listed on the Screen and the host remote. Equal scores share a rank. */
export interface RankedPlayer {
  id: string;
  name: string;
  color: string;
  avatar?: string;
  score: number;
  connected: boolean;
  rank: number;
}

/** A session total as the Screen and the host remote list it. Equal totals share a rank. */
export interface RankedTotal {
  id: string;
  name: string;
  color: string;
  avatar?: string;
  total: number;
  rank: number;
}

/**
 * A team as every view lists it, in index order (F81). Its score is the sum of its members'
 * scores; equal scores share a rank. `memberIds` are in join order.
 */
export interface TeamView {
  index: number;
  name: string;
  color: string;
  score: number;
  rank: number;
  memberIds: string[];
}

/** The night so far: totals of every finished game, players who left included. */
export interface SessionView {
  gameNumber: number;
  totals: RankedTotal[];
}

/** A question as the Screen sees it. `answer` is present only once that question is revealed. */
export interface ScreenQuestion {
  id: string;
  text: string;
  imageId?: string;
  points: number;
  answer?: string;
}

/** The answer timer as clients see it: the clients count down `seconds` themselves. */
export type AnswerTimerView = Pick<AnswerTimer, 'seconds' | 'up'>;

/** The buzz timer as clients see it: the clients count down `seconds` themselves. */
export type BuzzTimerView = Pick<BuzzTimer, 'seconds'>;

interface SharedRoomView {
  code: string;
  title: string;
  phase: Phase;
  questionIndex: number; // -1 in lobby
  questionCount: number;
  openingCounter: number;
  players: RankedPlayer[];
  winnerId: string | null;
  alsoBuzzed: BuzzGap[];
  lockedOut: string[];
  /** Who pressed before the buzzers opened, with false starts on (F71); not secret. */
  // SPEC-QUESTION: the spec's views carry no false start fields; see DECISIONS (F72).
  falseStarts: string[];
  showScoreboard: boolean;
  settings: RoomSettings;
  /** `host:judge` would be accepted: false during the wait before a reopen. */
  canJudge: boolean;
  /** `host:undo` would be accepted (DECISIONS F02: the client never derives this). */
  canUndo: boolean;
  /** The player judged correct on the current question, for the reveal; null if nobody was. */
  scorerId: string | null;
  answerTimer: AnswerTimerView | null;
  buzzTimer: BuzzTimerView | null;
  /** Ranked session totals from game 2 on; null during the room's first game (F76). */
  session: SessionView | null;
  /** Every team with its score and rank while teams are on; null when off (F81). */
  teams: TeamView[] | null;
}

/** Everything except answers, host notes and token data. */
export interface ScreenView extends SharedRoomView {
  role: 'screen';
  question: ScreenQuestion | null; // null in LOBBY
  /** The next question's image (in LOBBY, the first's), so the Screen can preload it. */
  nextImageId: string | null;
  /** The set's category and difficulty, for the title card; null when the set has none. */
  category: string | null;
  difficulty: Difficulty | null;
  /** Connected host remotes, not counting the Screen itself: the lobby folds its settings then. */
  hostDevices: number;
}

/** Everything, including the current and next question's answer and notes. */
export interface HostView extends SharedRoomView {
  role: 'host';
  question: Question | null;
  nextQuestion: Question | null;
  /** Join order (`joinedAt`, then id), not ranked, so rows never move under the host's thumb. */
  players: (RankedPlayer & { rttMs: number })[];
  buzzes: Buzz[];
  judgements: Judgement[];
}

/** A row of the phone's "Who's here" list. */
export interface LobbyPlayer {
  id: string;
  name: string;
  color: string;
  avatar?: string;
  connected: boolean;
}

/** Only what the phone needs. No question text in v1; the answer only after reveal. */
export interface PlayerView {
  role: 'player';
  code: string;
  phase: Phase;
  questionIndex: number;
  questionCount: number;
  openingCounter: number;
  me: { id: string; name: string; color: string; avatar?: string; score: number; rank: number };
  playerCount: number;
  hasBuzzed: boolean; // this opening
  /** A press now would count: OPEN or COLLECTING, not locked out, not buzzed or joined this opening. */
  canBuzz: boolean;
  lockedOut: boolean;
  /** Pressed before the buzzers opened, with false starts on; cleared by a later opening (F71). */
  falseStart: boolean;
  /** The room's false start wait; 0 is off, and then a press before the opening is ignored. */
  falseStartMs: FalseStartMs;
  winnerId: string | null;
  winnerName: string | null;
  /** Points this player gained or lost on the current question. */
  pointsThisQuestion: number;
  answerTimer: AnswerTimerView | null;
  buzzTimer: BuzzTimerView | null;
  /** Every player in join order, in LOBBY only; `null` in every other phase (DECISIONS F59). */
  lobby: LobbyPlayer[] | null;
  /** This player's night total and rank among `count` totals, from game 2 on; null in game 1 or
   * before their first tally (F77). Not the whole list: the phone shows only its own line. */
  // SPEC-QUESTION: the spec's PlayerView has no night total; see DECISIONS (F77).
  tonight: { total: number; rank: number; count: number } | null;
  /** What the results card draws, in FINAL only; null in every other phase (F78). */
  // SPEC-QUESTION: the spec's PlayerView has no ranking; see DECISIONS (F78).
  results: PlayerResults | null;
  /** As `SharedRoomView.teams`: every team, so the phone can show its own and its rank (F81). */
  teams: TeamView[] | null;
  answer?: string;
}

/** The top rows of a ranking and how many it has in all, for "and N more". */
export interface TopRows<R> {
  rows: R[];
  count: number;
}

/** The results card's data on the phone: the set title, the game's and the night's top rows. */
export interface PlayerResults {
  title: string;
  ranking: TopRows<RankedPlayer>;
  /** From game 2, as `SharedRoomView.session`; null in game 1. */
  tonight: TopRows<RankedTotal> | null;
}

export type View = ScreenView | HostView | PlayerView;

// ---------- Events ----------

/** Every client→server event acknowledges with this. */
export type Ack<T extends object = object> = ({ ok: true } & T) | { ok: false; error: string };

/** One-off events that drive sounds and animations. */
export type Fx =
  | { kind: 'buzz'; playerId: string; gaps: BuzzGap[] }
  | { kind: 'correct'; playerId: string; points: number }
  | { kind: 'wrong'; playerId: string }
  | { kind: 'timeUp'; playerId: string }
  | { kind: 'buzzTimeUp' }
  | { kind: 'join'; playerId: string }
  | { kind: 'practice'; playerId: string }
  | { kind: 'falseStart'; playerId: string };

export type JudgeResult = Judgement['result'];

/** Client→server payloads, keyed by Socket.IO event name. */
export interface ClientPayloads {
  'screen:join': { code: string; hostToken?: string }; // DECISIONS #2
  'host:join': { code: string; hostToken: string };
  'player:join': { code: string; playerId: string; name: string; avatar?: string };
  ping: { t: number };
  'player:buzz': Record<string, never>;
  'player:practice': Record<string, never>;
  'player:rename': { name: string };
  'player:leave': Record<string, never>;
  'host:start': Record<string, never>;
  'host:open': Record<string, never>;
  'host:judge': { result: JudgeResult };
  'host:reveal': Record<string, never>;
  'host:next': Record<string, never>;
  'host:prev': Record<string, never>;
  'host:scoreboard': { show: boolean };
  'host:undo': Record<string, never>;
  'host:adjustScore': { playerId: string; delta: number };
  'host:kick': { playerId: string };
  'host:settings': Partial<RoomSettings>;
  'host:setTeam': { playerId: string; team: number };
  'host:end': Record<string, never>;
}

export type ClientEvent = keyof ClientPayloads;

/** Typed Socket.IO maps: `Server<ClientToServerEvents, ServerToClientEvents>`. */
export type ClientToServerEvents = {
  [E in ClientEvent]: (payload: ClientPayloads[E], ack: (res: Ack) => void) => void;
};

export interface ServerToClientEvents {
  state: (view: View) => void;
  /** The client acks at once; the server times RTT from emit to ack (DECISIONS F15). */
  pong: (payload: { t: number }, ack: () => void) => void;
  fx: (fx: Fx) => void;
  kicked: (payload: Record<string, never>) => void;
  /** A host device joined: the Screen and the other remotes close their pairing QR (F38). */
  'host:paired': (payload: Record<string, never>) => void;
  'room:closed': (payload: { reason: string }) => void;
}

/** `POST /api/rooms` body and response. */
