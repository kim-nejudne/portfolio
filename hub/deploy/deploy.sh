#!/usr/bin/env bash
#
# Ships a fresh build to the droplet. A push to `main` that touches hub/ does
# this already (`.github/workflows/deploy-hub.yml`); this script is the same
# release done by hand, the break-glass path when Actions is the thing that is
# broken. Run from the hub directory, as `deploy`, never root:
#
#   HUB_HOST=deploy@host ./deploy/deploy.sh
#
# The target is required rather than defaulted. It used to default to the
# production droplet, which is convenient exactly once and wrong every other
# way: a hardcoded production host in a repo is a target string for anyone
# reading it, and a script that ships to production when run with no arguments
# has no safe way to be tried out. Export it once in your shell profile.
#
# The hub is static, so there is no image to build and no container to restart —
# this is a verify, a build, a precompress, a staged rsync and a swap that keeps
# the outgoing build in /var/www/hub.prev. Adapted from PLINTH's, which is the
# same shape.
#
# No chown and no nginx reload: /var/www/hub is deploy:www-data and nginx only
# reads it, the same arrangement as /var/www/poketrack. nginx's own config is
# root's and a person moves it.
#
# Two differences from PLINTH's, both because this is the apex domain:
#   1. `npm run verify` is a gate rather than a habit. The hub is the page a
#      recruiter sees first and the one nobody clicks *back* to — a broken
#      choreography here loses the visit outright, where a broken spoke loses one
#      of five. 95 assertions take under two minutes; shipping without them to
#      save that is a bad trade at any hour.
#   2. it serves two names, `kimnejudne.dev` and `www.`, and the www vhost is a
#      301 rather than a second copy.
set -euo pipefail

HOST="${HUB_HOST:?set HUB_HOST to the droplet, as deploy@host}"
REMOTE="/var/www/hub"

cd "$(dirname "$0")/.."

# The CV is a placeholder until this marker is deleted, and a button promising a
# CV over a stub PDF is worse than no button at all — the page would be making
# its one takeaway offer and then failing to honour it, in front of exactly the
# reader it was built for.
#
# The marker is a sidecar file rather than a string inside the PDF because
# chromium writes page text into a FlateDecode stream: a `grep` for a sentinel
# would never match, and this guard would pass in silence, which is the one
# failure mode a guard is not allowed to have.
#
# No override flag. An escape hatch on a gate whose entire purpose is to stop a
# known-bad file is a gate that will be escaped exactly when it matters. Checked
# before the build, because there is no reason to spend two minutes on a `dist/`
# that cannot ship.
#
# Written as `if` rather than the `[ -f X ] && { … }` this file uses elsewhere:
# that form survives `set -e` only by the &&-list exemption, and a guard whose
# correctness depends on a footnote in the bash manual is not a guard.
if [ -f cv/PLACEHOLDER ]; then
  echo "public/cv.pdf is still the placeholder — replace it, then rm cv/PLACEHOLDER (see cv/README.md)" >&2
  exit 1
fi

echo "==> Typecheck and build"
npm run build

DIST="dist"
[ -f "${DIST}/index.html" ] || { echo "no build output at ${DIST}" >&2; exit 1; }

# The case-study pages, checked one by one before anything ships.
#
# This is the guard against the worst failure this deploy has available to it.
# The pages are generated by `scripts/case-studies.mjs` from each spoke's own
# CASE-STUDY.md in a sibling directory, wired to npm's `prebuild`. Anything
# that bypasses that hook — `npx vite build` by hand, a `dist/` left over from
# an older checkout — produces a build with no `dist/work/`, and the rsync
# below runs with `--delete`. That would remove live URLs from the server
# while the homepage carries on linking to them, and every line of output would
# be green.
#
# The ids are written out rather than read from `src/spokes.ts`, because bash
# cannot import it. That duplication is safe only because `verify.mjs` does
# read the source and asserts the same set, so a spoke added there and
# forgotten here fails the gate above rather than shipping half-linked.
for spoke in poketrack ts-dojo; do
  [ -f "${DIST}/work/${spoke}/index.html" ] || {
    echo "missing ${DIST}/work/${spoke}/index.html — did prebuild run? try: npm run cases" >&2
    exit 1
  }
done

# And their index. Checked separately from the loop above because its failure
# mode is different: without it `/work/` does not 404, it **403**s. nginx
# resolves the directory through `try_files $uri $uri/`, finds no index and
# falls to autoindex, which is off. That URL is printed on the CV, which is a
# PDF that cannot be corrected once it has been emailed.
[ -f "${DIST}/work/index.html" ] || {
  echo "missing ${DIST}/work/index.html — did prebuild run? try: npm run cases" >&2
  exit 1
}

# And the CV, which reaches `dist/` only by sitting in `public/`. Anything
# hand-placed on the droplet is destroyed by the `--delete` below, so a CV that
# is not in this build is a 404 behind two buttons a minute from now.
[ -f "${DIST}/cv.pdf" ] || {
  echo "missing ${DIST}/cv.pdf — it belongs in public/, not on the server" >&2
  exit 1
}

# Against the freshly built `dist/`, served by `vite preview`. Not against the
# droplet: these assertions drive a headless browser through the whole scroll and
# several of them hide layers and push cards around to take their measurements,
# which is not something to do to a live site.
if [ "${HUB_SKIP_VERIFY:-}" != "1" ]; then
  echo "==> Verify (HUB_SKIP_VERIFY=1 to skip, and think about why)"
  npx vite preview --port 4501 >/dev/null 2>&1 &
  PREVIEW=$!
  trap 'kill ${PREVIEW} 2>/dev/null || true' EXIT
  sleep 3
  npm run verify
  kill "${PREVIEW}" 2>/dev/null || true
  trap - EXIT
fi

# gzip_static serves these instead of compressing per request. -9 is worth it
# here because it happens once at deploy rather than once per visitor.
#
# Images are deliberately excluded. AVIF and PNG are already compressed, gzip
# gains nothing on them, and the head layers are 7MB of the 8.2MB build — so
# compressing them would double the rsync for no benefit at all.
echo "==> Precompress"
find "$DIST" -type f \( -name '*.js' -o -name '*.css' -o -name '*.html' -o -name '*.svg' \) \
  -exec gzip -9 -k -f {} +

# Staged into hub.next, never straight into the live directory: a dropped
# connection mid-rsync would otherwise leave a half-written site serving.
# --delete so removed asset hashes don't accumulate in the stage.
echo "==> Stage to ${HOST}:${REMOTE}.next"
rsync -rltz --delete --chmod=D755,F644 "${DIST}/" "${HOST}:${REMOTE}.next/"

echo "==> Swap, keeping the outgoing build in ${REMOTE}.prev"
# shellcheck disable=SC2029 # REMOTE is meant to expand here, on the workstation.
ssh "$HOST" "
  set -e
  test -f ${REMOTE}.next/index.html
  rsync -a --delete ${REMOTE}/ ${REMOTE}.prev/
  rsync -a --delete ${REMOTE}.next/ ${REMOTE}/
"

./deploy/confirm.sh

cat <<EOF
==> Done: https://kimnejudne.dev

Rollback if this was wrong (one release back):
  ssh ${HOST} 'rsync -a --delete ${REMOTE}.prev/ ${REMOTE}/'
EOF
