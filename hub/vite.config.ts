import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { SPOKES } from './src/spokes';

/*
 * Absolute paths, built without `node:path`. `import.meta.url` is typed by
 * `vite/client`, which is already in the project; reaching for `node:path`
 * here would mean adding `@types/node` and `"node"` to `types`, and that
 * changes `setTimeout`'s return type across every file in `src/`.
 */
const here = (p: string) => new URL(p, import.meta.url).pathname;

export default defineConfig({
  plugins: [react(), tailwindcss()],
  build: {
    rollupOptions: {
      /*
       * Seven pages: the homepage, the case-study index, and one case study
       * per spoke.
       *
       * The shells under `work/` are generated by `scripts/case-studies.mjs`
       * (wired to `prebuild` and `predev`) from each spoke's own
       * `CASE-STUDY.md`. They are build output, not source, and are gitignored
       * alongside `dist/`.
       *
       * They have to live *inside* the project root. Vite derives an entry's
       * emitted path from its path relative to root, so `work/tallow/
       * index.html` becomes `dist/work/tallow/index.html`; anywhere outside
       * root and the relative path picks up `../` segments, at which point all
       * five collide on a single `index.html`.
       *
       * `index` must be relisted. Naming any input at all replaces the
       * implicit one, and dropping it here would silently stop emitting the
       * homepage — `deploy.sh` checks for `dist/index.html` before it ships,
       * which is the only reason that would not be catastrophic.
       */
      input: {
        index: here('./index.html'),
        /* The key must not collide with a spoke id, and `work` cannot: `SPOKES`
           ids are the five subdomains. */
        work: here('./work/index.html'),
        ...Object.fromEntries(SPOKES.map((s) => [s.id, here(`./work/${s.id}/index.html`)])),
      },
    },
  },
  server: { port: 4500, strictPort: true },
  preview: { port: 4501, strictPort: true },
});
