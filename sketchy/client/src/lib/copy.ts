export type CopyKey = keyof typeof EN;

export const COPY: Readonly<Record<CopyKey, string>> = EN;

/** Looks up a string and fills its placeholders. */
export type Translate = (key: CopyKey, vars?: Record<string, string | number>) => string;

/** Looks a key up in the English table and fills its `{name}` placeholders. */
export const t: Translate = (key, vars = {}) =>
  EN[key].replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
